#!/usr/bin/env bash
# Builds supabase/setup/production-setup.sql: every migration in order, the
# migration history (so `supabase db push` and the Supabase GitHub integration
# know they are applied), then seed.sql, in one transaction. For setting up a
# new Supabase project by pasting into the SQL Editor, with no command line.
# Run after adding a migration: scripts/build-setup-sql.sh
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/setup/production-setup.sql
{
  cat <<'HEAD'
-- =============================================================================
-- AWLEL: ONE-TIME DATABASE SETUP for a new Supabase project.
--
-- How to use: Supabase dashboard → SQL Editor → New query → paste this whole
-- file → Run. It takes a few seconds and should end with "Success".
--
-- It creates every table, security rule and storage bucket, records the
-- migrations as applied, and adds the starting content (categories, editorial
-- board, pages, and one SAMPLE issue you can delete later in the admin).
-- It runs as one transaction: if anything fails, nothing is changed.
-- If the database is already set up, it stops without changing anything.
--
-- GENERATED by scripts/build-setup-sql.sh from supabase/migrations and
-- supabase/seed.sql. Do not edit by hand.
-- =============================================================================
begin;

do $$
begin
  if to_regclass('public.issues') is not null then
    raise exception 'AWLEL is already set up in this database. Nothing was changed.';
  end if;
end $$;

HEAD
  for f in supabase/migrations/*.sql; do
    echo
    echo "-- >>> migration $(basename "$f")"
    cat "$f"
  done
  echo
  echo "-- >>> migration history (so the Supabase CLI and GitHub integration see these as applied)"
  echo "create schema if not exists supabase_migrations;"
  echo "create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);"
  for f in supabase/migrations/*.sql; do
    b=$(basename "$f" .sql)
    echo "insert into supabase_migrations.schema_migrations (version, name) values ('${b%%_*}', '${b#*_}') on conflict do nothing;"
  done
  echo
  echo "-- >>> seed.sql"
  cat supabase/seed.sql
  echo
  echo "commit;"
} > "$out"
echo "Wrote $out ($(wc -l < "$out") lines)"
