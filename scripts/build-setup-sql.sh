#!/usr/bin/env bash
# Builds supabase/setup/production-setup.sql for setting up or updating a
# Supabase project by pasting into the SQL Editor, with no command line.
# It applies only the migrations the database hasn't recorded yet (the same
# history `supabase db push` and the Supabase GitHub integration use), adds
# the starting content only to an empty site, and ends with a status table.
# Run after adding a migration: scripts/build-setup-sql.sh
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/setup/production-setup.sql
versions=$(for f in supabase/migrations/*.sql; do b=$(basename "$f"); printf "'%s'," "${b%%_*}"; done)
versions=${versions%,}
{
  cat <<HEAD
-- =============================================================================
-- AWLEL: DATABASE SETUP AND UPDATES for Supabase.
--
-- How to use: Supabase dashboard → SQL Editor → New query → paste this whole
-- file → Run. It finishes with a small table showing the database's status.
--
-- Safe to run any number of times:
--   * a new project gets every table, security rule and storage bucket, plus
--     the starting content (categories, editorial board, pages and one SAMPLE
--     issue you can delete later in the admin);
--   * an existing AWLEL database only gets the updates it is missing;
--   * an up-to-date database is left unchanged.
-- Everything runs in one transaction: if anything fails, nothing is changed.
--
-- GENERATED by scripts/build-setup-sql.sh from supabase/migrations and
-- supabase/seed.sql. Do not edit by hand.
-- =============================================================================
begin;

-- The migration history the Supabase CLI and GitHub integration also use.
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);

do \$awlel_check\$
begin
  if to_regclass('public.issues') is not null
     and not exists (select 1 from supabase_migrations.schema_migrations where version in ($versions)) then
    raise exception 'This database has AWLEL tables but no record of how they were created, so updating it automatically is not safe. Nothing was changed. Ask the developer for help.';
  end if;
end
\$awlel_check\$;
HEAD
  for f in supabase/migrations/*.sql; do
    b=$(basename "$f" .sql)
    v=${b%%_*}
    n=${b#*_}
    echo
    echo "-- >>> migration $b"
    echo "do \$awlel_wrap\$"
    echo "begin"
    echo "  if not exists (select 1 from supabase_migrations.schema_migrations where version = '$v') then"
    echo "    execute \$awlel_migration\$"
    cat "$f"
    echo "\$awlel_migration\$;"
    echo "    insert into supabase_migrations.schema_migrations (version, name) values ('$v', '$n');"
    echo "    raise notice 'Applied update $v ($n)';"
    echo "  end if;"
    echo "end"
    echo "\$awlel_wrap\$;"
  done
  echo
  echo "-- >>> starting content (seed.sql), only for a site that has none yet"
  echo "do \$awlel_wrap\$"
  echo "begin"
  echo "  if not exists (select 1 from public.site_settings) then"
  echo "    execute \$awlel_seed\$"
  cat supabase/seed.sql
  echo "\$awlel_seed\$;"
  echo "    raise notice 'Added the starting content';"
  echo "  end if;"
  echo "end"
  echo "\$awlel_wrap\$;"
  echo
  echo "commit;"
  cat <<TAIL

-- >>> status
select 'Database updates applied' as item,
       (select count(*) from supabase_migrations.schema_migrations where version in ($versions))::text
         || ' of $(ls supabase/migrations/*.sql | wc -l | tr -d ' ')' as status
union all select 'Subject categories', (select count(*) from public.categories)::text
union all select 'Static pages', (select count(*) from public.pages)::text
union all select 'Published issues', (select count(*) from public.issues where status = 'published')::text
union all select 'Storage buckets', (select count(*) from storage.buckets where id in ('issue-covers', 'site-assets', 'published-files', 'submissions'))::text || ' of 4'
union all select 'Super Admins', (select count(*) from public.profiles where role = 'super_admin')::text;
TAIL
} > "$out"
echo "Wrote $out ($(wc -l < "$out") lines)"
